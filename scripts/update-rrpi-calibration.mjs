import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const inputPath = resolve(process.argv[2] ?? "data/statcan/18100286.csv");
const outputPath = resolve(process.argv[3] ?? "src/lib/pricing/rrpi-generated.ts");

const PROJECT_GROUPS = new Set([
  "Flooring",
  "Interior additions or remodels",
  "Plumbing fixtures and equipment",
  "Property improvements",
  "Windows and doors",
]);

const GEOGRAPHY_MAP = [
  { output: "Ontario", matches: [/^Ontario$/i] },
  { output: "Toronto", matches: [/^Toronto$/i, /Toronto/i] },
  { output: "Ottawa", matches: [/Ottawa/i] },
  { output: "Southwestern Ontario", matches: [/^London$/i, /London/i] },
];

function parseCsv(text) {
  const rows = [];
  let field = "";
  let row = [];
  let inQuotes = false;

  for (let index = 0; index < text.length; index += 1) {
    const char = text[index];
    const next = text[index + 1];

    if (char === '"' && next === '"') {
      field += '"';
      index += 1;
      continue;
    }

    if (char === '"') {
      inQuotes = !inQuotes;
      continue;
    }

    if (char === "," && !inQuotes) {
      row.push(field);
      field = "";
      continue;
    }

    if ((char === "\n" || char === "\r") && !inQuotes) {
      if (char === "\r" && next === "\n") {
        index += 1;
      }

      row.push(field);
      field = "";
      if (row.some((value) => value.length > 0)) {
        rows.push(row);
      }
      row = [];
      continue;
    }

    field += char;
  }

  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }

  const [headers, ...dataRows] = rows;
  return dataRows.map((dataRow) =>
    Object.fromEntries(headers.map((header, index) => [header, dataRow[index] ?? ""])),
  );
}

function projectGroupFromRow(row) {
  const value = row["Project type"] ?? row["Project group"] ?? row["Renovation project group"] ?? "";
  return PROJECT_GROUPS.has(value) ? value : undefined;
}

function geographyFromRow(row) {
  const geo = row.GEO ?? row.Geography ?? "";
  return GEOGRAPHY_MAP.find((candidate) => candidate.matches.some((pattern) => pattern.test(geo)))?.output;
}

function periodKey(period) {
  return period.replace(/[^0-9Q]/gi, "");
}

const csv = readFileSync(inputPath, "utf8");
const rows = parseCsv(csv);
const records = rows
  .map((row) => ({
    geography: geographyFromRow(row),
    projectGroup: projectGroupFromRow(row),
    referencePeriod: row.REF_DATE ?? row["Reference period"] ?? "",
    value: Number(row.VALUE ?? row.Value),
  }))
  .filter((record) => record.geography && record.projectGroup && record.referencePeriod && Number.isFinite(record.value));

const latestPeriod = records
  .map((record) => record.referencePeriod)
  .sort((left, right) => periodKey(left).localeCompare(periodKey(right)))
  .at(-1);

if (!latestPeriod) {
  throw new Error(`No usable RRPI records found in ${inputPath}`);
}

const latestRecords = records.filter((record) => record.referencePeriod === latestPeriod);
const ontarioByProject = new Map(
  latestRecords
    .filter((record) => record.geography === "Ontario")
    .map((record) => [record.projectGroup, record.value]),
);

const generated = latestRecords
  .filter((record) => record.geography !== "Ontario")
  .map((record) => {
    const ontarioValue = ontarioByProject.get(record.projectGroup);
    if (!ontarioValue) {
      return undefined;
    }

    return {
      geography: record.geography,
      projectGroup: record.projectGroup,
      referencePeriod: latestPeriod,
      relativeToOntario: Math.round((record.value / ontarioValue) * 1000) / 1000,
    };
  })
  .filter(Boolean)
  .sort((left, right) =>
    `${left.geography}:${left.projectGroup}`.localeCompare(`${right.geography}:${right.projectGroup}`),
  );

const output = `import type { RrpiSeedRecord } from "@/lib/pricing/rrpi-calibration";

// Generated by scripts/update-rrpi-calibration.mjs from Statistics Canada table 18-10-0286-01.
// Source CSV: ${inputPath}
export const RRPI_GENERATED_SEED: RrpiSeedRecord[] = ${JSON.stringify(generated, null, 2)};
`;

writeFileSync(outputPath, output);
console.log(`Wrote ${generated.length} RRPI calibration records for ${latestPeriod} to ${outputPath}`);
